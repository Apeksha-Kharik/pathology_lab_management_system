const { sendWhatsAppMessage } = require('./whatsappService');
const { sendEmail } = require('../config/email');
const { generateReceiptPdf, generateReportPdf } = require('./patientPdfService');

const emailPatientPdf = async ({ to, subject, text, generate }) => {
 if (!to) return { sent: false, skipped: true };
 try {
  const { buffer, filename } = await generate();
  const result = await sendEmail({ to, subject, text, attachments: [{ filename, content: buffer, contentType: 'application/pdf' }] });
  if (!result.sent) console.error('Patient PDF email failed:', result.code || result.error || 'Email not accepted');
  return result;
 } catch (error) { console.error('Patient PDF email failed:', error.message); return { sent: false }; }
};

const sendBoth = async (whatsapp, email) => {
 const [message, mail] = await Promise.allSettled([Promise.resolve().then(whatsapp), Promise.resolve().then(email)]);
 if (message.status === 'rejected') console.error('Patient WhatsApp failed:', message.reason?.message);
 return { ...(message.status === 'fulfilled' ? message.value : { sent: false }),
  email: mail.status === 'fulfilled' ? mail.value : { sent: false } };
};

const notifyBookingRequested = async (booking) => {
 try {
  const amount = 'INR ' + Number(booking.amount).toFixed(2);
  const body = `IndiPath: We received your ${booking.testName} booking request. The receptionist will confirm or reject it.\n\nBooking ID: ${booking.bookingCode}\nDate: ${booking.bookingDate}\nTime Slot: ${booking.timeSlot}\nAmount: ${amount}`;
  return await sendWhatsAppMessage({ to: booking.phone || booking.userId?.phone, event: 'booking_requested', body,
   parameters: [booking.name, booking.bookingCode, booking.testName, booking.bookingDate, booking.timeSlot, amount] });
 } catch (error) { console.error('Booking WhatsApp notification failed:', error.message); return { sent: false }; }
};

const notifyBookingConfirmed = async (booking) => {
 try {
  const amount = 'INR ' + Number(booking.amount).toFixed(2);
  const body = `IndiPath: Your ${booking.testName} booking has been confirmed by the receptionist.\n\nPatient ID: ${booking.patientCode}\nBooking ID: ${booking.bookingCode}\nDate: ${booking.bookingDate}\nTime Slot: ${booking.timeSlot}\nAmount: ${amount}`;
  return await sendWhatsAppMessage({ to: booking.phone || booking.userId?.phone, event: 'booking_confirmed', body,
   parameters: [booking.name, booking.patientCode, booking.bookingCode, booking.testName, booking.bookingDate, booking.timeSlot, amount] });
 } catch (error) { console.error('Confirmation WhatsApp notification failed:', error.message); return { sent: false }; }
};

const notifyReceiptReady = async booking => {
 try {
  if (booking.paymentStatus !== 'Paid') return { sent: false, skipped: true };
  return await sendWhatsAppMessage({ to: booking.phone || booking.userId?.phone, event: 'receipt_ready',
   body: `IndiPath: Hello ${booking.name}, your receipt has been generated by the receptionist and is ready.\n\nBooking ID: ${booking.bookingCode}\nReceipt ID: ${booking.receiptId || booking.receiptNumber || 'N/A'}\nTest/package: ${booking.testName}\nAmount: INR ${Number(booking.amount).toFixed(2)}\nPlease log in to your patient dashboard to view and download your receipt.` });
 } catch (error) { console.error('Receipt ready notification failed:', error.message); return { sent: false }; }
};

// Notification failures must not undo saved payments or approvals.
const notifyPaymentReceived = async (booking) => {
 try {
  if (booking.paymentStatus !== 'Paid') return { sent: false, skipped: true };
  const body = `IndiPath: Hello ${booking.name}, your payment has been received.\n\nBooking ID: ${booking.bookingCode}\nReceipt ID: ${booking.receiptId || booking.receiptNumber || 'N/A'}\nTest/package: ${booking.testName}\nAmount: INR ${Number(booking.amount).toFixed(2)}\nPlease log in to your patient dashboard to download your receipt.`;
  return await sendBoth(
   () => sendWhatsAppMessage({ to: booking.phone || booking.userId?.phone, event: 'payment_received', body }),
   () => emailPatientPdf({ to: booking.email || booking.userId?.email, subject: `IndiPath receipt - ${booking.bookingCode}`,
    text: `Hello ${booking.name}, your payment of INR ${Number(booking.amount).toFixed(2)} has been received. Your receipt for booking ${booking.bookingCode} is attached.`,
    generate: () => generateReceiptPdf(booking) })
  );
 } catch (error) { console.error('Receipt WhatsApp notification failed:', error.message); return { sent: false }; }
};
const notifyReportReady = async (report) => {
 try {
  if (report.status !== 'Approved') return { sent: false, skipped: true };
  const booking = report.bookingId;
  const body = `IndiPath: Hello ${booking.name}, your report has been approved and is ready.\n\nBooking ID: ${booking.bookingCode}\nTest/package: ${booking.testName || report.testName}\nPlease log in to your patient dashboard to view and download your report.`;
  return await sendBoth(
   () => sendWhatsAppMessage({ to: booking.phone || report.userId?.phone, event: 'report_ready', body }),
   () => emailPatientPdf({ to: booking.email || report.userId?.email, subject: `IndiPath report ready - ${booking.bookingCode}`,
    text: `Hello ${booking.name}, your approved report for booking ${booking.bookingCode} is attached.`,
    generate: () => generateReportPdf(report) })
  );
 } catch (error) { console.error('Report WhatsApp notification failed:', error.message); return { sent: false }; }
};
// Routine progress remains visible in the app without WhatsApp messages.
const notifySampleCollected = async () => ({ sent: false, skipped: true });
module.exports = { notifyBookingRequested, notifyBookingConfirmed, notifyPaymentReceived, notifyReportReady, notifySampleCollected, notifyReceiptReady };
